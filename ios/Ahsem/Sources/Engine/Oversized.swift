import Foundation

/// كشف القرار الأكبر من أدوات الحسم العادية.
///
/// «أستقيل؟» لا تجاوبه ثلاثة أسئلة وشبكة تقييم — يحتاج تفكيكاً. الكشف محلي بلا
/// نداء شبكة: يشتغل مع كل حرف يكتبه المستخدم، ونداء الشبكة هنا يكلف مالاً
/// وزمناً على فحص أغلب نتائجه «لا، قرار عادي».
///
/// قائمة كلمات مقصودة لا تصنيف ذكي: قرارات المصير مفرداتها محدودة (وظيفة،
/// زواج، هجرة، عقار، دراسة...) والقائمة تمسكها بصفر تكلفة. الخطأ المقبول هنا هو
/// الفائت لا الزائف — لافتة «قرارك مصيري» فوق برجر وسوشي تُضحك الناس على
/// التطبيق، وفوات حالة نادرة الصياغة يغطيه اختيار المستخدم فئة «قرار مصيري».
enum Oversized {

    /// كلمات كاملة بعد التطبيع (أ→ا، ة→ه، بلا تشكيل)
    private static let words: Set<String> = [
        "بيت", "شقه", "عقار", "ارض", "قرض",
        "بلد", "شركه", "محل",
        "جامعه", "كليه", "ماجستير", "دكتوراه",
        "ابتعث", "الابتعاث", "بعثه",
        "هجره", "اهاجر", "نهاجر",
        "اتزوج", "نتزوج", "زواج", "خطبه", "اخطب",
        "طلاق", "اطلق",
        "استقالتي", "استقالته",
    ]

    /// جذور تُطابق بداية الكلمة — أربعة أحرف فأكثر حتى لا تبتلع كلمة بريئة.
    /// «بيت» لا تصلح جذراً: «بيتزا» تبدأ بها.
    private static let stems: [String] = [
        "استقيل",
        "استقال",
        "وظيف",   // وظيفه، وظيفتي، الوظيفه (بعد قص ال)
        "مشروع",  // مشروعي، مشروعك
        "تخصص",
        "استثمر",
        "استثمار",
    ]

    private static func matches(token: String) -> Bool {
        // «الوظيفه» — نجرب الكلمة ومجردة من «ال»
        let forms = token.hasPrefix("ال") ? [token, String(token.dropFirst(2))] : [token]
        return forms.contains { form in
            words.contains(form) || stems.contains { form.hasPrefix($0) }
        }
    }

    /// - Parameters:
    ///   - labels: الخيارات المكتوبة
    ///   - categoryId: اختيار المستخدم فئة «قرار مصيري» إعلانٌ صريح بالحجم يغني عن الكلمات
    static func looksOversized(labels: [String], categoryId: String?) -> Bool {
        if categoryId == "life" { return true }
        return labels.contains { label in
            ArabicText.tokens(label).contains(where: matches)
        }
    }
}
